/**
 * Returns translated string for a given key in current locale
 */
export function getLocalizedString(key: string, locale: LocaleCode = 'en'): string {
  if (STRING_RESOURCES[locale]?.[key]) {
    return STRING_RESOURCES[locale][key];
  }
  // Fallback to English
  if (STRING_RESOURCES.en?.[key]) {
    return STRING_RESOURCES.en[key];
  }
  return key;
}

/**
 * Resolves content whether it is a string key reference (@string/...) or raw text
 */
export function resolveContent(content: string, locale: LocaleCode = 'en'): string {
  if (!content) return '';
  if (content.startsWith('@string/')) {
    const key = content.replace('@string/', '');
    return getLocalizedString(key, locale);
  }
  return content;
}
